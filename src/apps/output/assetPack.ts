import { markdownToBlocks } from "./markdown";
import { extractPalette, roledSwatches, type PaletteSwatch } from "./palette";
import { extractFonts, googleFontsHref, type BrandFonts } from "./typography";

/*
 * A designer-ready .zip built client-side from a result's own colour palette, fonts and (if any)
 * generated logo concepts: a visual swatch sheet, a real Adobe Swatch Exchange file, a plain-text
 * cheat sheet of fonts/colours/CSS variables, and the logo images. No server call, no cost.
 */

function hexToRgb(hex: string): { r: number; g: number; b: number } {
  const n = hex.replace("#", "");
  return { r: parseInt(n.slice(0, 2), 16), g: parseInt(n.slice(2, 4), 16), b: parseInt(n.slice(4, 6), 16) };
}

function roundRectPath(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, r: number) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}

/** A high-res PNG swatch sheet: one card per colour, with its name, hex and RGB values. */
async function paletteCanvasPng(palette: PaletteSwatch[], brandName: string): Promise<Blob> {
  const cols = Math.min(4, Math.max(1, palette.length));
  const rows = Math.ceil(palette.length / cols);
  const cell = 300;
  const pad = 48;
  const headerH = 96;
  const width = pad * 2 + cols * cell;
  const height = headerH + pad + rows * cell;
  const scale = 2; // retina-res output
  const canvas = document.createElement("canvas");
  canvas.width = width * scale;
  canvas.height = height * scale;
  const ctx = canvas.getContext("2d")!;
  ctx.scale(scale, scale);
  ctx.fillStyle = "#ffffff";
  ctx.fillRect(0, 0, width, height);
  ctx.fillStyle = "#111111";
  ctx.font = "bold 30px Arial, sans-serif";
  ctx.fillText(`${brandName} — Colour Palette`, pad, 50);
  ctx.font = "15px Arial, sans-serif";
  ctx.fillStyle = "#6b6b6b";
  ctx.fillText("Generated by EZYOURLIFE", pad, 76);

  palette.forEach((s, i) => {
    const col = i % cols;
    const row = Math.floor(i / cols);
    const x = pad + col * cell;
    const y = headerH + pad + row * cell;
    const swatchSize = cell - 56;
    ctx.fillStyle = s.hex;
    ctx.strokeStyle = "#111111";
    ctx.lineWidth = 2;
    roundRectPath(ctx, x, y, swatchSize, swatchSize - 66, 14);
    ctx.fill();
    ctx.stroke();
    const rgb = hexToRgb(s.hex);
    ctx.fillStyle = "#111111";
    ctx.font = "bold 19px Arial, sans-serif";
    ctx.fillText(s.name, x, y + swatchSize - 38);
    ctx.font = "14px Menlo, Consolas, monospace";
    ctx.fillStyle = "#555555";
    ctx.fillText(`${s.hex.toUpperCase()}  ·  RGB ${rgb.r}, ${rgb.g}, ${rgb.b}`, x, y + swatchSize - 14);
  });

  return new Promise((resolve, reject) => {
    canvas.toBlob((b) => (b ? resolve(b) : reject(new Error("Could not render the palette image."))), "image/png");
  });
}

/**
 * A valid Adobe Swatch Exchange (.ase) binary: "ASEF" signature, version 1.0, one RGB colour
 * entry block per swatch. Every multi-byte field in the ASE format is big-endian.
 */
function buildAse(palette: PaletteSwatch[]): Uint8Array {
  const blocks: Uint8Array[] = palette.map((s) => {
    const name = s.name || s.hex;
    const codes = Array.from(name).map((c) => c.charCodeAt(0));
    const nameLen = codes.length + 1; // includes the trailing null terminator, per the ASE spec
    const n = s.hex.replace("#", "");
    const r = parseInt(n.slice(0, 2), 16) / 255;
    const g = parseInt(n.slice(2, 4), 16) / 255;
    const b = parseInt(n.slice(4, 6), 16) / 255;

    const dataLen = 2 + nameLen * 2 + 4 + 12 + 2; // nameLen + name(incl. null) + "RGB " + 3×float32 + colour type
    const buf = new ArrayBuffer(6 + dataLen);
    const v = new DataView(buf);
    let o = 0;
    v.setUint16(o, 0x0001, false); // block type: colour entry
    o += 2;
    v.setUint32(o, dataLen, false);
    o += 4;
    v.setUint16(o, nameLen, false);
    o += 2;
    for (const code of codes) {
      v.setUint16(o, code, false);
      o += 2;
    }
    v.setUint16(o, 0, false); // null terminator
    o += 2;
    v.setUint8(o, 0x52); // "RGB "
    v.setUint8(o + 1, 0x47);
    v.setUint8(o + 2, 0x42);
    v.setUint8(o + 3, 0x20);
    o += 4;
    v.setFloat32(o, r, false);
    o += 4;
    v.setFloat32(o, g, false);
    o += 4;
    v.setFloat32(o, b, false);
    o += 4;
    v.setUint16(o, 2, false); // colour type: Normal
    return new Uint8Array(buf);
  });

  const total = blocks.reduce((n, b) => n + b.length, 0);
  const out = new Uint8Array(12 + total);
  const head = new DataView(out.buffer, 0, 12);
  head.setUint8(0, 0x41); // "ASEF"
  head.setUint8(1, 0x53);
  head.setUint8(2, 0x45);
  head.setUint8(3, 0x46);
  head.setUint16(4, 1, false); // version 1.0
  head.setUint16(6, 0, false);
  head.setUint32(8, blocks.length, false);
  let offset = 12;
  for (const b of blocks) {
    out.set(b, offset);
    offset += b.length;
  }
  return out;
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "colour";

/** Fonts, colours (hex + RGB) and ready-to-paste CSS variables, in one plain-text cheat sheet. */
function buildFontsAndColorsText(palette: PaletteSwatch[], fonts: BrandFonts, brandName: string): string {
  const roled = roledSwatches(palette);
  const lines: string[] = [`${brandName} — Fonts & Colours`, "Generated by EZYOURLIFE", ""];

  lines.push("COLOURS");
  for (const { role, swatch } of roled) {
    const rgb = hexToRgb(swatch.hex);
    lines.push(`  ${role.padEnd(11)} ${swatch.name.padEnd(20)} ${swatch.hex.toUpperCase()}   RGB(${rgb.r}, ${rgb.g}, ${rgb.b})`);
  }

  const href = googleFontsHref(fonts);
  if (fonts.heading || fonts.body) {
    lines.push("", "FONTS");
    if (fonts.heading) lines.push(`  Heading: ${fonts.heading}`);
    if (fonts.body) lines.push(`  Body:    ${fonts.body}`);
    if (href) {
      lines.push(`  Google Fonts stylesheet: ${href}`);
      lines.push(`  Embed in HTML:           <link rel="stylesheet" href="${href}">`);
    }
  }

  lines.push("", "CSS VARIABLES — paste into your site's stylesheet", ":root {");
  for (const { role, swatch } of roled) lines.push(`  --color-${slug(role)}: ${swatch.hex.toLowerCase()}; /* ${swatch.name} */`);
  if (fonts.heading) lines.push(`  --font-heading: "${fonts.heading}", Georgia, serif;`);
  if (fonts.body) lines.push(`  --font-body: "${fonts.body}", system-ui, sans-serif;`);
  lines.push("}");

  return lines.join("\n");
}

export interface AssetPackOptions {
  text: string;
  brandName: string;
  /** Ready logo concept images (data: URLs), if any have been generated yet. */
  logoUrls?: string[];
}

/** Builds the whole .zip in memory and returns it, ready to hand to saveFile(). */
export async function buildBrandAssetsZip({ text, brandName, logoUrls }: AssetPackOptions): Promise<Blob> {
  const { blocks } = markdownToBlocks(text);
  const { palette } = extractPalette(blocks);
  if (palette.length < 2) throw new Error("No colour palette to pack yet.");
  const fonts = extractFonts(text);

  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();
  zip.file("palette.png", await paletteCanvasPng(palette, brandName));
  zip.file("palette.ase", buildAse(palette));
  zip.file("fonts-and-colors.txt", buildFontsAndColorsText(palette, fonts, brandName));
  const logos = (logoUrls ?? []).filter(Boolean);
  if (logos.length) {
    const folder = zip.folder("logos")!;
    logos.forEach((url, i) => {
      const base64 = url.split(",")[1];
      if (base64) folder.file(`logo-concept-${i + 1}.png`, base64, { base64: true });
    });
  }
  return zip.generateAsync({ type: "blob" });
}
