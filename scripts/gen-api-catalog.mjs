// Writes supabase/functions/_shared/apiCatalog.ts: for every app the public API can run,
// the inputs it takes (from src/apps/defs) and which server function runs it.
// Run after adding or changing apps:  node scripts/gen-api-catalog.mjs
// `--check` fails (exit 1) when the file is out of date, for CI.
import fs from "node:fs";
import path from "node:path";
import { loadApps, displayPrice, ROOT } from "./lib/load-apps.mjs";

const OUT = path.join(ROOT, "supabase/functions/_shared/apiCatalog.ts");

const d = await loadApps();

/** Keeps only what a caller needs to build a form. */
function cleanField(f) {
  const out = { key: f.key, label: f.label ?? f.key, type: f.type ?? "text" };
  if (f.required) out.required = true;
  if (f.placeholder) out.placeholder = String(f.placeholder);
  if (Array.isArray(f.options) && f.options.length) out.options = f.options.map(String);
  if (f.default !== undefined) out.default = String(f.default);
  if (f.help) out.help = String(f.help);
  if (f.profile) out.profile = f.profile;
  if (Array.isArray(f.columns)) out.columns = f.columns.map((c) => ({ key: c.key, label: c.label ?? c.key, type: c.type ?? "text" }));
  return out;
}

function cleanSample(s) {
  if (!s || typeof s !== "object") return undefined;
  const out = {};
  for (const [k, v] of Object.entries(s)) {
    if (typeof v === "string") out[k] = v;
    else if (Array.isArray(v)) out[k] = v.map((r) => ({ ...r }));
  }
  return Object.keys(out).length ? out : undefined;
}

const RUNNABLE_FLAGSHIP = new Set(["interview", "analyse", "plan", "pack"]);
const catalog = {};

for (const [id, def] of Object.entries(d.APPS).sort(([a], [b]) => a.localeCompare(b))) {
  const spec = d.APP_SPECS[id];
  if (!spec) continue; // browser-only engines (calculators, converters, presets) are not on the API
  const flag = spec.flagship;
  let runner;
  let mode;
  if (flag) {
    if (RUNNABLE_FLAGSHIP.has(flag.shell)) { runner = "flagship-app"; mode = flag.shell === "analyse" ? "document" : "form"; }
    else if (flag.shell === "studio") { runner = "flagship-app"; mode = "studio"; }
    else continue; // coaching sessions need the website
  } else {
    if (def.engine === "tracker") continue; // needs the tracker's own table
    runner = "ai-app";
    mode = { doc: "form", chat: "chat", vision: "images", image: "image" }[def.engine] ?? (spec.kind === "chat" ? "chat" : spec.kind === "vision" ? "images" : spec.kind === "image" ? "image" : "form");
  }
  const entry = {
    runner,
    mode,
    engine: def.engine,
    kind: spec.kind,
    charge: spec.chargeId ?? id,
    credits: spec.credits ?? displayPrice(d, id) ?? 1,
    intro: def.intro,
  };
  if (def.cta) entry.cta = def.cta;
  if (Array.isArray(def.fields)) entry.fields = def.fields.map(cleanField);
  if (def.engine === "image") {
    entry.promptLabel = def.promptLabel;
    if (def.styles?.length) entry.styles = def.styles;
    if (def.aspects?.length) entry.aspects = def.aspects;
  }
  if (def.engine === "chat" && def.suggestions?.length) entry.suggestions = def.suggestions;
  if (flag?.shell === "studio" && Array.isArray(spec.flagship.variants)) entry.variants = spec.flagship.variants.map((v) => (typeof v === "string" ? v : v.id ?? v.name)).filter(Boolean);
  const sample = cleanSample(def.sample);
  if (sample) entry.sample = sample;
  catalog[id] = entry;
}

const body = `// GENERATED by scripts/gen-api-catalog.mjs from src/apps/defs and _shared/appSpecs. Do not edit by hand.
// The apps the public API (supabase/functions/api) can run, with the inputs each one takes.
export interface ApiField { key: string; label: string; type: string; required?: boolean; placeholder?: string; options?: string[]; default?: string; help?: string; profile?: string; columns?: { key: string; label: string; type: string }[] }
export interface ApiApp { runner: "ai-app" | "flagship-app"; mode: "form" | "chat" | "images" | "image" | "document" | "studio"; engine: string; kind: string; charge: string; credits: number; intro: string; cta?: string; fields?: ApiField[]; promptLabel?: string; styles?: string[]; aspects?: string[]; suggestions?: string[]; variants?: string[]; sample?: Record<string, unknown> }
export const API_CATALOG: Record<string, ApiApp> = ${JSON.stringify(catalog, null, 1)};
`;

if (process.argv.includes("--check")) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (now !== body) { console.error("apiCatalog.ts is out of date: run node scripts/gen-api-catalog.mjs"); process.exit(1); }
  console.log(`apiCatalog.ts is up to date (${Object.keys(catalog).length} apps).`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${path.relative(ROOT, OUT)}: ${Object.keys(catalog).length} apps.`);
}
