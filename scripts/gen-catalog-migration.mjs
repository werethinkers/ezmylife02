// npm run gen:catalog -- <vertical>   (or --all)
// Writes the SQL file that adds a vertical's catalogue rows to tools_catalog, from the data
// file in src/data/catalog/. Rows are never typed by hand.
//
// - Only inserts: "ON CONFLICT (id) DO NOTHING" means an app that is already live is never
//   renamed, re-priced or changed by these files.
// - Rows already written to an earlier catalogue file are skipped, so running it twice is safe.
// - `placements` (where else the app shows, src/data/placements.ts) is the one field that can change
//   later: a row whose placements differ from every earlier file gets an UPDATE line for just that.
// - --dry prints the SQL instead of writing a file.
import fs from "node:fs";
import path from "node:path";
import { loadApps, ROOT } from "./lib/load-apps.mjs";

const args = process.argv.slice(2);
const dry = args.includes("--dry");
const all = args.includes("--all");
const wanted = args.filter((a) => !a.startsWith("--"));
const MIGRATIONS = path.join(ROOT, "supabase/migrations");

const d = await loadApps();
const groups = Object.keys(d.CATALOG_GROUPS);
const verticals = all ? groups : wanted;
if (!verticals.length) {
  console.error(`Say which vertical: npm run gen:catalog -- <vertical>\nAvailable: ${groups.join(", ") || "(none yet — add a file in src/data/catalog/)"}`);
  process.exit(1);
}
for (const v of verticals) {
  if (!d.CATALOG_GROUPS[v]) {
    console.error(`No vertical "${v}" in src/data/catalog/index.ts. Available: ${groups.join(", ") || "(none)"}`);
    process.exit(1);
  }
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `ARRAY[${a.map(q).join(", ")}]` : "'{}'::text[]");

// Ids that an earlier generated file already inserts, and placement lines it already wrote.
const done = new Set();
const writtenSql = [];
for (const f of fs.readdirSync(MIGRATIONS).sort()) {
  if (!/_catalog_/.test(f)) continue;
  const sql = fs.readFileSync(path.join(MIGRATIONS, f), "utf8");
  if (!sql.startsWith("-- Generated by scripts/gen-catalog-migration.mjs")) continue;
  writtenSql.push(sql);
  for (const m of sql.matchAll(/^\s*\('((?:[^']|'')+)',/gm)) done.add(m[1].replace(/''/g, "'"));
}
const placeLine = (r) => `UPDATE public.tools_catalog SET placements = ${arr(r.placements ?? [])} WHERE id = ${q(r.id)};`;
// The newest earlier line for an id decides what the database already has.
const lastPlaced = new Map();
for (const sql of writtenSql) for (const m of sql.matchAll(/^UPDATE public\.tools_catalog SET placements = .* WHERE id = '((?:[^']|'')+)';$/gm)) lastPlaced.set(m[1].replace(/''/g, "'"), m[0]);

const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
let n = 0;
for (const v of verticals) {
  const rows = d.CATALOG_GROUPS[v].filter((r) => !done.has(r.id));
  // Placements for every row (new or old) that has them and that no earlier file set the same way.
  const placeSql = d.CATALOG_GROUPS[v]
    .filter((r) => (r.placements?.length || lastPlaced.has(r.id)) && lastPlaced.get(r.id) !== placeLine(r))
    .map(placeLine);
  if (!rows.length && !placeSql.length) {
    console.log(`${v}: nothing new (all ${d.CATALOG_GROUPS[v].length} rows are already in an earlier file).`);
    continue;
  }
  const values = rows.map((r) =>
    `  (${[q(r.id), q(r.name), q(r.description), q(r.category), arr(r.toolType), q(r.source), r.isLive ? "true" : "false", "false", "false", r.dedicatedRoute ? q(r.dedicatedRoute) : "NULL", Number.isInteger(r.displayOrder) ? r.displayOrder : 0, arr(r.alsoIn ?? [])].join(", ")})`,
  );
  // Every category the rows use gets a catalog_categories row (insert-only), so the admin list
  // and the home page know it. Wording comes from CATEGORY_INFO in src/data/goals.ts.
  const usedCategories = [...new Set(rows.flatMap((r) => [r.category, ...(r.alsoIn ?? [])]))].filter((c) => d.CATEGORY_INFO[c]);
  const categorySql = usedCategories.length
    ? `INSERT INTO public.catalog_categories (name, goal, line, give, get_text, kind, doc_give, doc_get)\nVALUES\n${usedCategories
        .map((c) => {
          const i = d.CATEGORY_INFO[c];
          return `  (${[q(c), q(i.goal), q(i.line), q(i.give), q(i.get), q(i.kind), i.docGive ? q(i.docGive) : "NULL", i.docGet ? q(i.docGet) : "NULL"].join(", ")})`;
        })
        .join(",\n")}\nON CONFLICT (name) DO NOTHING;\n\n`
    : "";
  const chunks = [];
  for (let i = 0; i < values.length; i += 200) chunks.push(values.slice(i, i + 200));
  const sql =
    `-- Generated by scripts/gen-catalog-migration.mjs from src/data/catalog/ (vertical: ${v}). Do not edit by hand.\n` +
    `-- Adds ${rows.length} app${rows.length === 1 ? "" : "s"} to the catalogue. Existing rows are left exactly as they are, except for their placements.\n` +
    categorySql +
    chunks
      .map((c) => `INSERT INTO public.tools_catalog (id, name, description, category, tool_types, source, is_live, is_premium, is_free, dedicated_route, display_order, extra_categories)\nVALUES\n${c.join(",\n")}\nON CONFLICT (id) DO NOTHING;\n`)
      .join("\n") +
    (placeSql.length ? `\n-- Where the apps show (src/data/placements.ts).\n${placeSql.join("\n")}\n` : "");
  if (dry) {
    console.log(sql);
  } else {
    // One second apart so two verticals in one run get different file names.
    const name = `${String(BigInt(stamp) + BigInt(n))}_catalog_${v.replace(/[^a-z0-9]+/gi, "_").toLowerCase()}.sql`;
    fs.writeFileSync(path.join(MIGRATIONS, name), sql);
    console.log(`${v}: wrote supabase/migrations/${name} (${rows.length} rows, ${placeSql.length} placement lines).`);
  }
  n++;
}
if (!dry && n) console.log(`\nNext: run "npm run check:apps", then apply the file to the live database (see docs/launch-plan.md, "How changes go live").`);
