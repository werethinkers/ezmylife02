// npm run gen:catalog -- <vertical>   (or --all)
// Writes the SQL file that adds a vertical's catalogue rows to tools_catalog, from the data
// file in src/data/catalog/. Rows are never typed by hand.
//
// - Only inserts: "ON CONFLICT (id) DO NOTHING" means an app that is already live is never
//   renamed, re-priced or changed by these files.
// - Rows already written to an earlier catalogue file are skipped, so running it twice is safe.
// - --dry prints the SQL instead of writing a file.
import fs from "node:fs";
import path from "node:path";
import { loadApps, ROOT } from "./lib/load-apps.mjs";

const args = process.argv.slice(2);
const dry = args.includes("--dry");
const all = args.includes("--all");
const wanted = args.filter((a) => !a.startsWith("--"));
const MIGRATIONS = path.join(ROOT, "supabase/migrations");

const d = await loadApps();
const groups = Object.keys(d.CATALOG_GROUPS);
const verticals = all ? groups : wanted;
if (!verticals.length) {
  console.error(`Say which vertical: npm run gen:catalog -- <vertical>\nAvailable: ${groups.join(", ") || "(none yet — add a file in src/data/catalog/)"}`);
  process.exit(1);
}
for (const v of verticals) {
  if (!d.CATALOG_GROUPS[v]) {
    console.error(`No vertical "${v}" in src/data/catalog/index.ts. Available: ${groups.join(", ") || "(none)"}`);
    process.exit(1);
  }
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `ARRAY[${a.map(q).join(", ")}]` : "'{}'::text[]");

// Ids that an earlier generated file already inserts.
const done = new Set();
for (const f of fs.readdirSync(MIGRATIONS)) {
  if (!/_catalog_/.test(f)) continue;
  const sql = fs.readFileSync(path.join(MIGRATIONS, f), "utf8");
  if (!sql.startsWith("-- Generated by scripts/gen-catalog-migration.mjs")) continue;
  for (const m of sql.matchAll(/^\s*\('((?:[^']|'')+)',/gm)) done.add(m[1].replace(/''/g, "'"));
}

const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
let n = 0;
for (const v of verticals) {
  const rows = d.CATALOG_GROUPS[v].filter((r) => !done.has(r.id));
  if (!rows.length) {
    console.log(`${v}: nothing new (all ${d.CATALOG_GROUPS[v].length} rows are already in an earlier file).`);
    continue;
  }
  const values = rows.map((r) =>
    `  (${[q(r.id), q(r.name), q(r.description), q(r.category), arr(r.toolType), q(r.source), r.isLive ? "true" : "false", "false", "false", r.dedicatedRoute ? q(r.dedicatedRoute) : "NULL", Number.isInteger(r.displayOrder) ? r.displayOrder : 0].join(", ")})`,
  );
  const chunks = [];
  for (let i = 0; i < values.length; i += 200) chunks.push(values.slice(i, i + 200));
  const sql =
    `-- Generated by scripts/gen-catalog-migration.mjs from src/data/catalog/ (vertical: ${v}). Do not edit by hand.\n` +
    `-- Adds ${rows.length} app${rows.length === 1 ? "" : "s"} to the catalogue. Existing rows are left exactly as they are.\n` +
    chunks
      .map((c) => `INSERT INTO public.tools_catalog (id, name, description, category, tool_types, source, is_live, is_premium, is_free, dedicated_route, display_order)\nVALUES\n${c.join(",\n")}\nON CONFLICT (id) DO NOTHING;\n`)
      .join("\n");
  if (dry) {
    console.log(sql);
  } else {
    // One second apart so two verticals in one run get different file names.
    const name = `${String(BigInt(stamp) + BigInt(n))}_catalog_${v.replace(/[^a-z0-9]+/gi, "_").toLowerCase()}.sql`;
    fs.writeFileSync(path.join(MIGRATIONS, name), sql);
    console.log(`${v}: wrote supabase/migrations/${name} (${rows.length} rows).`);
  }
  n++;
}
if (!dry && n) console.log(`\nNext: run "npm run check:apps", then apply the file to the live database (see docs/launch-plan.md, "How changes go live").`);
