// node scripts/gen-recategorise-migration.mjs [stamp]
// Writes the migration that splits crowded categories into smaller ones (Oct 2026).
// Reads the new categories from src/data/goals.ts and the apps that now sit in them from the
// catalogue files, so nothing is typed by hand. Safe to run twice: categories are inserted only if
// missing, and an app is moved only while it is still in its old category (a change made in
// admin since then is left alone). No app is renamed, re-priced or deleted.
import fs from "node:fs";
import path from "node:path";
import { loadApps, ROOT } from "./lib/load-apps.mjs";

/** New category → the category its apps came from. */
const SPLITS = {
  "ID & Exam Photos": "Image Tools",
  "Photo Enhance & Retouch": "Image Tools",
  "Blur & Privacy": "Image Tools",
  "Social Media Sizes": "Image Tools",
  "Writing & Editors": "Research",
};

const d = await loadApps();
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const seed = Object.keys(SPLITS)
  .map((name) => {
    const i = d.CATEGORY_INFO[name];
    if (!i) throw new Error(`${name} is not in CATEGORY_INFO`);
    return `  (${[q(name), q(i.goal), q(i.line), q(i.give), q(i.get), q(i.kind), i.docGive ? q(i.docGive) : "NULL", i.docGet ? q(i.docGet) : "NULL"].join(", ")})`;
  })
  .join(",\n");

const moved = d.catalogue.filter((t) => SPLITS[t.category]);
const updates = moved
  .map((t) => {
    const extra = (t.alsoIn ?? []).length ? `, extra_categories = ARRAY[${t.alsoIn.map(q).join(", ")}]` : "";
    return `UPDATE public.tools_catalog SET category = ${q(t.category)}${extra} WHERE id = ${q(t.id)} AND category = ${q(SPLITS[t.category])};`;
  })
  .join("\n");

const research = d.CATEGORY_INFO.Research;
const sql = `-- Generated by scripts/gen-recategorise-migration.mjs. Do not edit by hand.
-- Splits Image Tools (75 apps) and Research into smaller categories so every app is easy to find.
-- Moves ${moved.length} apps. Names, prices and pages stay the same.

INSERT INTO public.catalog_categories (name, goal, line, give, get_text, kind, doc_give, doc_get)
VALUES
${seed}
ON CONFLICT (name) DO NOTHING;

-- Research no longer holds the editors; say what is left in it (only if nobody changed the line in admin).
UPDATE public.catalog_categories SET line = ${q(research.line)}, updated_at = now()
  WHERE name = 'Research' AND line = 'Turn scans into text and edit long documents.';

${updates}
`;
const stamp = process.argv[2] || new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
const file = `${stamp}_catalog_split_categories.sql`;
fs.writeFileSync(path.join(ROOT, "supabase/migrations", file), sql);
console.log(`wrote supabase/migrations/${file}: ${Object.keys(SPLITS).length} categories, ${moved.length} apps moved`);
