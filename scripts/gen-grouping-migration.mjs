// node scripts/gen-grouping-migration.mjs
// One-off: writes the migration that adds the editable category list (catalog_categories) and the
// "also in" column on tools_catalog, seeds the categories from src/data/goals.ts, and records the
// extra categories of the apps already in the catalogue files. Everything is additive and safe to
// run twice: nothing is renamed, re-priced or deleted.
import fs from "node:fs";
import path from "node:path";
import { loadApps, ROOT } from "./lib/load-apps.mjs";

const d = await loadApps();
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = Object.entries(d.CATEGORY_INFO).map(([name, i]) => {
  const goalOrder = d.GOALS.findIndex((g) => g.id === i.goal);
  return { name, i, goalOrder };
});
const seed = rows
  .map(({ name, i }) => `  (${[q(name), q(i.goal), q(i.line), q(i.give), q(i.get), q(i.kind), i.docGive ? q(i.docGive) : "NULL", i.docGet ? q(i.docGet) : "NULL"].join(", ")})`)
  .join(",\n");

const extras = Object.values(d.CATALOG_GROUPS).flat().filter((r) => (r.alsoIn ?? []).length);
const updates = extras
  .map((r) => `UPDATE public.tools_catalog SET extra_categories = ARRAY[${r.alsoIn.map(q).join(", ")}] WHERE id = ${q(r.id)} AND extra_categories = '{}';`)
  .join("\n");

const sql = `-- Generated by scripts/gen-grouping-migration.mjs. Do not edit by hand.
-- Editable groupings: a category list the admin can change, and apps that sit in more than one category.
-- Additive only. Existing apps keep their main category, name and price.

CREATE TABLE IF NOT EXISTS public.catalog_categories (
  name        text PRIMARY KEY,
  goal        text NOT NULL DEFAULT 'more',
  line        text NOT NULL DEFAULT '',
  give        text NOT NULL DEFAULT 'a few details',
  get_text    text NOT NULL DEFAULT 'your result',
  kind        text NOT NULL DEFAULT 'document' CHECK (kind IN ('quick', 'photo', 'document', 'sheet')),
  doc_give    text,
  doc_get     text,
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.catalog_categories ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can view categories" ON public.catalog_categories;
CREATE POLICY "Anyone can view categories" ON public.catalog_categories FOR SELECT USING (true);
DROP POLICY IF EXISTS "Admins can add categories" ON public.catalog_categories;
CREATE POLICY "Admins can add categories" ON public.catalog_categories FOR INSERT TO authenticated WITH CHECK (has_role(auth.uid(), 'admin'::app_role));
DROP POLICY IF EXISTS "Admins can change categories" ON public.catalog_categories;
CREATE POLICY "Admins can change categories" ON public.catalog_categories FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'admin'::app_role));

ALTER TABLE public.tools_catalog ADD COLUMN IF NOT EXISTS extra_categories text[] NOT NULL DEFAULT '{}';

INSERT INTO public.catalog_categories (name, goal, line, give, get_text, kind, doc_give, doc_get)
VALUES
${seed}
ON CONFLICT (name) DO NOTHING;

${updates}
`;
const stamp = process.argv[2] || new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
const file = `${stamp}_catalog_groupings.sql`;
fs.writeFileSync(path.join(ROOT, "supabase/migrations", file), sql);
console.log(`wrote supabase/migrations/${file}: ${rows.length} categories, ${extras.length} apps with extra categories`);
