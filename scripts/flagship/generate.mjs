// node scripts/flagship/generate.mjs [category ...]   (no argument: every file in ./data)
//
// Writes the four files every flagship category needs, from one data file each, so an app is
// written once and the catalogue row, app definition, price and server instructions can never
// disagree:
//   src/data/catalog/flagship-<cat>.ts                       catalogue rows
//   src/apps/defs/flagship-<cat>.ts                          the app screen (form, shell, sections)
//   src/apps/prices/flagship-<cat>.ts                        price shown on the page
//   supabase/functions/_shared/appSpecs/flagship-<cat>.ts    instructions and price charged
// and adds the category's one import line and one entry line to each folder's groups file.
// Then run: npm run check:apps && npm run gen:catalog -- flagship<Cat>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../..");
const DATA = path.join(HERE, "data");

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const exportName = (cat) => camel(`flagship-${cat}`);
const HEADER = (cat) => `// Generated by scripts/flagship/generate.mjs from scripts/flagship/data/${cat}.mjs. Edit the data file and run the generator; do not edit this file by hand.`;
const j = (v) => JSON.stringify(v, null, 2).replace(/\n/g, "\n  ");

const NOTE_LINE = {
  legal: "A draft for reference, not legal advice. Have a lawyer review it before you rely on it.",
  money: "General information for planning, not financial advice. Check with a SEBI-registered adviser or a CA before acting.",
  health: "General information, not medical advice. Talk to your doctor before making changes.",
  official: "Rules, fees and dates change. Check the official website named in the result before you apply or pay.",
};

function clientDef(a) {
  const base = {
    engine: a.shell,
    intro: a.intro,
    steps: a.steps,
    related: a.related,
    credits: a.credits,
    fields: a.fields ?? [],
    sample: a.sample ?? {},
    youGet: a.youGet ?? a.sections ?? [],
    fileName: a.fileName ?? a.id,
    ...(a.refine ? { refineChips: a.refine } : {}),
    ...(a.pictures ? { pictures: a.pictures } : {}),
  };
  const note = a.note ?? (a.notes ?? []).map((n) => NOTE_LINE[n]).filter(Boolean).join(" ");
  if (note) base.note = note;
  switch (a.shell) {
    case "interview":
      return { ...base, minAnswers: a.min ?? 6, maxAnswers: a.max ?? 20, voice: a.voice ?? true, cta: a.cta ?? "Make my book" };
    case "analyse":
      return { ...base, upload: a.upload, cta: a.cta ?? "Make my report" };
    case "studio":
      return { ...base, variants: a.variants.map(({ key, label, hint }) => ({ key, label, hint })), photo: a.photo };
    case "plan":
    case "pack":
      return { ...base, pages: a.pages.map(([title, keys]) => ({ title, keys })), cta: a.cta ?? (a.shell === "plan" ? "Make my plan" : "Make my pack") };
    case "coach":
      return { ...base, suggestions: a.suggestions ?? [], voice: a.voice ?? false, turns: a.turns ?? 20, cta: a.cta ?? "Start my session" };
    default:
      throw new Error(`${a.id}: unknown shell "${a.shell}"`);
  }
}

function serverSpec(a) {
  // Keyed by the field's label, same as the key the client sends each value under
  // (src/apps/shell/Fields.tsx's serializeValues) — so the server can reject a value that is
  // longer than the form ever let someone type, without trusting the client to have enforced it.
  const fieldLimits = Object.fromEntries((a.fields ?? []).filter((f) => f.maxLength).map((f) => [f.label, f.maxLength]));
  const s = {
    credits: a.credits,
    role: a.role ?? "You are a professional photographer and retoucher.",
    deliverable: a.deliverable ?? "pictures",
    sections: a.sections ?? [],
    ...(a.rules ? { rules: a.rules } : {}),
    ...(a.notes ? { notes: a.notes } : {}),
    ...(a.guide ? { guide: a.guide } : {}),
    ...(a.shell === "interview" ? { maxTurns: a.max ?? 20 } : {}),
    ...(a.shell === "coach" ? { maxTurns: a.turns ?? 20 } : {}),
    ...(a.variants ? { variants: Object.fromEntries(a.variants.map((v) => [v.key, v.prompt])) } : {}),
    ...(a.pictures ? { imageStyle: a.imageStyle ?? "Clean, professional, warm natural light." } : {}),
    ...(a.maxTokens ? { maxTokens: a.maxTokens } : {}),
    ...(Object.keys(fieldLimits).length ? { fieldLimits } : {}),
  };
  return `flagship(${JSON.stringify(a.shell)}, ${j(s)})`;
}

function check(a, cat) {
  // Photo studios make pictures, not documents, so they have no sections, role or deliverable.
  const need = ["id", "name", "desc", "category", "shell", "credits", "intro", "steps", "related", ...(a.shell === "studio" ? [] : ["sections", "role", "deliverable"])];
  for (const k of need) if (a[k] === undefined) throw new Error(`${cat}/${a.id ?? "?"}: missing "${k}"`);
  if (a.shell === "studio" && !a.variants?.length) throw new Error(`${a.id}: studio apps need variants`);
  if ((a.shell === "plan" || a.shell === "pack") && !a.pages?.length) throw new Error(`${a.id}: plan and pack apps need pages`);
  if (a.shell === "analyse" && !a.upload) throw new Error(`${a.id}: analyse apps need upload`);
  if (a.shell === "plan" || a.shell === "pack") {
    const keys = new Set((a.fields ?? []).map((f) => f.key));
    const onPages = new Set(a.pages.flatMap(([, k]) => k));
    for (const k of onPages) if (!keys.has(k)) throw new Error(`${a.id}: page lists "${k}", which is not a field`);
    for (const k of keys) if (!onPages.has(k)) throw new Error(`${a.id}: field "${k}" is on no page`);
  }
}

/** Adds one import line and one entry line to a union-merged groups file, if not there yet. */
function addToGroups(file, importLine, entryLine) {
  const p = path.join(ROOT, file);
  let src = fs.readFileSync(p, "utf8");
  if (src.includes(importLine)) return;
  const lines = src.split("\n");
  const lastImport = lines.reduce((n, l, i) => (l.startsWith("import ") ? i : n), -1);
  lines.splice(lastImport + 1, 0, importLine);
  src = lines.join("\n");
  const close = src.lastIndexOf("\n};");
  src = `${src.slice(0, close)}\n${entryLine}${src.slice(close)}`;
  fs.writeFileSync(p, src);
}

const wanted = process.argv.slice(2);
const files = fs.readdirSync(DATA).filter((f) => f.endsWith(".mjs")).map((f) => f.replace(/\.mjs$/, ""));
const cats = wanted.length ? wanted : files;
let total = 0;
for (const cat of cats) {
  const { apps } = await import(pathToFileURL(path.join(DATA, `${cat}.mjs`)).href);
  const name = exportName(cat);
  for (const a of apps) check(a, cat);
  const ids = apps.map((a) => a.id);
  const dup = ids.find((id, i) => ids.indexOf(id) !== i);
  if (dup) throw new Error(`${cat}: id "${dup}" is used twice`);

  const rows = apps.map((a) => ({
    id: a.id,
    name: a.name,
    description: a.desc,
    category: a.category,
    ...(a.alsoIn ? { alsoIn: a.alsoIn } : {}),
    toolType: a.types?.length ? a.types : ["AI Apps"],
    source: "featured",
    isLive: true,
  }));
  fs.writeFileSync(
    path.join(ROOT, `src/data/catalog/flagship-${cat}.ts`),
    `import type { ToolEntry } from "../toolsDatabase";\n\n${HEADER(cat)}\nexport const ${name}: ToolEntry[] = [\n${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}\n];\n`,
  );
  fs.writeFileSync(
    path.join(ROOT, `src/apps/defs/flagship-${cat}.ts`),
    `import type { AppDef } from "../types";\n\n${HEADER(cat)}\nexport const ${name}: Record<string, AppDef> = {\n${apps.map((a) => `  ${JSON.stringify(a.id)}: ${j(clientDef(a))},`).join("\n")}\n};\n`,
  );
  fs.writeFileSync(
    path.join(ROOT, `src/apps/prices/flagship-${cat}.ts`),
    `${HEADER(cat)}\n// Priced with the shared rule (AI cost per run × 3 ÷ ₹0.376, rounded up to 5); see /mnt/project-files/flagship/flagship-app-costs.csv.\nexport const ${name}: Record<string, number> = {\n${apps.map((a) => `  ${JSON.stringify(a.id)}: ${a.credits},`).join("\n")}\n};\n`,
  );
  fs.writeFileSync(
    path.join(ROOT, `supabase/functions/_shared/appSpecs/flagship-${cat}.ts`),
    `import type { AppSpec } from "./base.ts";\nimport { flagship } from "./flagship-base.ts";\n\n${HEADER(cat)}\nexport const ${name}: Record<string, AppSpec> = {\n${apps.map((a) => `  ${JSON.stringify(a.id)}: ${serverSpec(a)},`).join("\n")}\n};\n`,
  );
  addToGroups("src/data/catalog/index.ts", `import { ${name} } from "./flagship-${cat}";`, `  ${name},`);
  addToGroups("src/apps/defs/groups.ts", `import { ${name} } from "./flagship-${cat}";`, `  "flagship-${cat}": ${name},`);
  addToGroups("src/apps/prices/groups.ts", `import { ${name} } from "./flagship-${cat}";`, `  "flagship-${cat}": ${name},`);
  addToGroups("supabase/functions/_shared/appSpecs/groups.ts", `import { ${name} } from "./flagship-${cat}.ts";`, `  "flagship-${cat}": ${name},`);
  console.log(`${cat}: ${apps.length} apps`);
  total += apps.length;
}
// Prices every flagship app shares (follow-up questions, pictures).
addToGroups("src/apps/prices/groups.ts", `import { flagshipCommon } from "./flagship-common";`, `  "flagship-common": flagshipCommon,`);
addToGroups("supabase/functions/_shared/appSpecs/groups.ts", `import { flagshipCommon } from "./flagship-common.ts";`, `  "flagship-common": flagshipCommon,`);
console.log(`${total} flagship apps written.`);
